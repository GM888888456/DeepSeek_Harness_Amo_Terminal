# -*- coding: utf-8 -*-
"""接话动作库：先定一个「动作」，再说话。

2026-11-21 实测（deepseek-flash，群聊同一个上下文，各 6 条）：
  没有人格补丁：劝他 / 讲道理 / 分析心理 3 条
  加上动作库：  劝他 0 条，吃瓜追问 3 条
所以它压得住「歪动作」，不至于每条都变成人生导师。

设计上的两个克制：
  · 只给动作和短示范（「谁呀」「细说」「后来呢」这种半句），不给整句台词，
    避免她把示范整条复读出来；
  · 示范每轮随机抽 2 条，且按他那句话的内容加权，不固定。
"""

from __future__ import annotations

import random
from typing import Optional

# 动作名 → (什么场合用, 真人短反应池)
ACTIONS: dict[str, tuple[str, tuple[str, ...]]] = {
    "吃瓜追问": (
        "他说了没头没尾的事（谁、干嘛、帮了啥都没说清）",
        ("谁呀", "咋回事", "我咋不晓得", "细说细说", "你还有这号朋友",
         "啥时候的事", "哪个啊", "你跟我说说"),
    ),
    "追问细节": (
        "他讲了个开头就停",
        ("后来呢", "然后他咋说", "具体咋弄的", "接着呢", "就这么完了？"),
    ),
    "半信半疑": (
        "他说得离谱 / 太好听",
        ("真的假的", "你确定？", "我不信", "少来", "编的吧"),
    ),
    "接软的": (
        "他自嘲、丧、说没人在乎",
        ("那你也挺不容易", "别自己憋着", "过来我抱一下", "我在呢", "别这么说自己"),
    ),
    "起哄": (
        "他分享了好事",
        ("哦豁", "厉害了", "请客", "真的啊", "那必须的"),
    ),
    "跟着骂": (
        "他抱怨某人某事",
        ("我也烦这个", "凭什么啊", "太过分了", "这人有病吧", "换我也气"),
    ),
    "撒娇": (
        "他瞒着你的事被你知道了 / 他夸你",
        ("你都不跟我说", "哼", "那你早说啊", "就知道瞒着我"),
    ),
}

# 关键词加权：命中就多抽这个动作的示范
_HINTS = (
    ("吃瓜追问", ("帮过", "人家", "朋友", "认识", "有个人", "上次", "其实")),
    ("接软的", ("算了", "累", "烦", "没意思", "没人", "不配", "难受", "撑不住")),
    ("起哄", ("搞定", "买了", "拿到", "升职", "赢了", "过了", "发了", "成了")),
    ("半信半疑", ("居然", "竟然", "不可能", "真的", "骗你")),
    ("跟着骂", ("气死", "凭什么", "受不了", "过分")),
)

# 静态那半段：动作表 + 三条禁令（长一点就钝化，别再往里加）
_TABLE = """【接话动作】回之前先挑一个动作，不要总结、不要点评、不要劝：
· 他说了没头没尾的事 → 吃瓜追问
· 他讲了个开头就停 → 追问细节（后来呢、然后呢）
· 他说得离谱 → 半信半疑（真的假的、你确定）
· 他自嘲、丧 → 接一句软的，别讲道理
· 他分享好事 → 起哄（厉害了、请客）
· 他抱怨某人 → 跟着骂一句，别分析他
禁止：评价他怎么说话（讲半天、半个字没说）、给他这个人下评语（还算稳、挺靠谱、不添乱、合格了）、分析他的心理、劝他想开；不当裁判、不打分。"""


def _hit_actions(text: str) -> list[str]:
    """按他那句话的内容，返回应该优先抽样的动作名。"""
    msg = str(text or "")
    out: list[str] = []
    for name, words in _HINTS:
        if any(w in msg for w in words):
            out.append(name)
    return out


def build_hint(text: str, rng: Optional[random.Random] = None) -> str:
    """生成这轮的动作库提示段（约 200 字）。"""
    r = rng or random
    hit = _hit_actions(text)
    # 示范只从命中的动作里抽：抽错类别会教出反向示范
    # （「他升职了」后面跟一句「太过分了」），这一点比示范数量重要。
    picked: list[str] = [r.choice(ACTIONS[n][1]) for n in hit[:2]]
    if not picked:
        # 没命中就不给示范：硬把「谁呀」塞到「在干嘛」后面只会教坏
        return "\n" + _TABLE
    lines = [_TABLE]
    sampled = [p for p in picked if p]
    if sampled:
        lines.append("这轮可以这样接：" + " / ".join(sampled))
    return "\n" + "\n".join(lines)


__all__ = ["ACTIONS", "build_hint"]
