def match_scene(place: str, zone: str = "") -> str:
    """地点 → 固定环境描述。命中不了就按地点字符串稳定地选一条兜底。

    顺序：地点里有明确的「不在写字楼」线索 → 按地点；否则 zone → 再按地点 → 兜底。
    ``zone`` 只在她待在室内、地点又没给线索时才算数。
    """
    text = str(place or "").strip()
    key = str(zone or "").strip().lower()
    # 2026-11-26（用户口径）：她是大小姐，坐 A8 后排——车上可以自拍、可以拍窗外，
    # 所以「车内」优先于 zone=road 的街道取景。
    if any(w in text for w in ("车上", "车内", "后排", "坐车", "车厢")):
        return ZONE_SCENES.get("car", "")
    # 2026-11-26：庄园/泳池要最先判——否则「山庄」里的「山」会命中户外强关键词，
    # 跳过 zone，最后落到「家 → 温馨房间」。
    if any(w in text for w in ("庄园", "山庄", "主楼", "门房", "车道")):
        return ZONE_SCENES.get("estate", "")
    if any(w in text for w in ("泳池", "池边")):
        return ZONE_SCENES.get("pool", "")
    # 2026-11-26（用户口径）：她的「路上」= 坐车（老周开），不是走街上；
    # 地铁/公交/站台/走路 才按街道或车站取景。
    if key == "road" and not any(w in text for w in ("地铁", "公交", "站台", "候车", "人行道", "步行", "走路")):
        return ZONE_SCENES.get("car", "")
    strong = bool(text) and any(word in text for word in PLACE_STRONG)
    if key in ZONE_SCENES and not strong:
        return ZONE_SCENES[key]
    if text:
        for words, scene in SCENE_MAP:
            if any(word in text for word in words):
                return scene
    if key in ZONE_SCENES:
        return ZONE_SCENES[key]
    if not text:
        return ""
    index = int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:8], 16)
    return FALLBACK_SCENES[index % len(FALLBACK_SCENES)]


