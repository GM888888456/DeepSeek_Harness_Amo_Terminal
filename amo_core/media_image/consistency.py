#: 自拍只钉一条物理事实：一只手拿着手机。机位、构图、姿势、表情都交给模型随场景发挥，
#: 不设固定姿势池（用户 2026-11-15 定：不要固定姿态，让她自己发挥）。
def _pick(pool, seed: str = "") -> str:
    """同一颗种子取同一条；没种子就用第一条（保持旧默认不变）。"""
    text = str(seed or "")
    if not text:
        return pool[0]
    index = int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:8], 16) % len(pool)
    return pool[index]


