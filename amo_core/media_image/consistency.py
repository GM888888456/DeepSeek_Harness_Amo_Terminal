def place_words_scene(text: str = "") -> str:
    """从提示词里认出地点词，返回对应场景；认不出返回空。"""
    body = str(text or "")
    if not body:
        return ""
    for words, zone in PLACE_WORDS:
        for word in words:
            if word in body:
                return ZONE_SCENES.get(zone, "")
    return ""
