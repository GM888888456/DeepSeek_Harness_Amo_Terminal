def _color_of(name: str) -> str:
    """取名字里的主色。

    「黑白玉簪」这种双色要保留成「黑白」，不能只取第一个「黑」——
    以前它会变成「黑小件」，看起来像漏了字。
    """
    for word in _COLORS:
        if word in name:
            # 双色：颜色后面紧跟另一个颜色词（黑白/粉白/灰蓝…）
            for other in _COLORS:
                if other != word and (word + other) in name:
                    return word + other
            return word
    return ""


def _style_of(name: str) -> str:
    for words, text in _GARMENT_STYLES:
        if any(word in name for word in words):
            return text
    return ""


def market_pattern(name: str) -> str:
    """市场衣服按「款式 + 颜色」生成固定花纹。同一个名字永远同一句。

    「汉服·唐制黑齐胸襦裙」→「黑色齐胸襦裙，裙身满绣缠枝花…」
    认不出款式 → 纯色兜底（绝不让模型自己编花纹）。
    """
    text = str(name or "").strip()
    if not text:
        return ""
    # 去掉「汉服·」「JK·」「制服·」这类前缀，只留款型与颜色
    body = text.split("·", 1)[-1].strip() if "·" in text else text
    color = _color_of(body)
    style = _style_of(body)
    if not style:
        return PLAIN_PATTERN
    if not color or color in style:
        return style
    # 颜色直接贴在款式前：粉色格纹裙 / 黑色水手服 / 黑白发饰
    return "%s色%s" % (color, style)


def set_pattern(look: str = "") -> str:
    """按「此刻穿着」找这套衣服的固定纹样；认不出套名就退回纯色。

    ``look`` 是衣柜里的整套描述，形如
    「JK·樱粉｜短袖白衬衫，JK·樱粉｜樱粉格裙，…」。取第一个「套名｜件名」的
    套名后半段（樱粉）去表里查；查不到再拿套名整体查一次。
    同一套永远返回同一句，这是「花纹不再变」的唯一依据。
    """
    text = str(look or "").strip()
    if not text:
        return ""
    head = text.split("，", 1)[0].split(",", 1)[0].strip()
    name = head.split("｜", 1)[0].strip() if "｜" in head else head
    if not name:
        return ""
    if name in SET_PATTERN:
        return SET_PATTERN[name]
    tail = name.split("·", 1)[1].strip() if "·" in name else ""
    if tail:
        if tail in SET_PATTERN:
            return SET_PATTERN[tail]
        for key, value in SET_PATTERN.items():
            if key and key in name:
                return value
    # 内置套名查不到 → 当成市场衣服，按「款式 + 颜色」推一条确定的花纹
    generated = market_pattern(name)
    if generated:
        return generated
    # 什么款式都认不出（西装、休闲服）：纯色，不编花纹
    return PLAIN_PATTERN


def set_form(look: str = "") -> str:
    """按套名取一句服装形制；认不出套名但看着是汉服，用 FORM_PLAIN。

    解析规则和 set_pattern 保持一致：先看「套名」整体，再看「·」后面的部分。
    """
    text = str(look or "").strip()
    if not text:
        return ""
    head = text.split("，", 1)[0].split(",", 1)[0].strip()
    name = head.split("｜", 1)[0].strip() if "｜" in head else head
    if not name:
        return ""
    if name in SET_FORM:
        return SET_FORM[name]
    tail = name.split("·", 1)[1].strip() if "·" in name else ""
    if tail and tail in SET_FORM:
        return SET_FORM[tail]
    for key, value in SET_FORM.items():
        if key and key in name:
            return value
    if "私密" in name:
        return PRIVATE_FORM
    if "寝衣" in name:
        return NIGHT_FORM
    # 2026-11-21：衣柜里 10 套 JK 外显改名「百褶」，判定上仍然是 JK（提示词里照写 JK 制服）
    if ("JK" in name.upper() or "制服" in name or "水手" in name
            or "格裙" in name or "百褶" in name):
        return JK_FORM
    if "汉服" in name:
        return FORM_PLAIN
    return ""


def form_clause(look: str = "") -> str:
    """给提示词用的形制句；不是汉服就不加。"""
    value = set_form(look)
    if not value:
        return ""
    return value if value.startswith("服装形制") else ("服装形制（必须一致）：" + value)


def pattern_clause(look: str = "") -> str:
    """给提示词用的纹样句；没有衣服就不加。"""
    value = set_pattern(look)
    return ("布料纹样（必须一致）：" + value) if value else ""


def split_prompts(text: str, limit: int = 4) -> list[str]:
    """一条指令里要好几张图时，按换行 / 分号 / 竖线切开。

    只切明确的分隔符，不猜「和」——「猫和狗」是一张图，不是两张。
    """
    raw = str(text or "")
    for sep in ("\n", "；", ";", "|", "｜"):
        raw = raw.replace(sep, "\u0000")
    parts = [item.strip() for item in raw.split("\u0000")]
    return [item for item in parts if item][: max(1, int(limit or 1))]

